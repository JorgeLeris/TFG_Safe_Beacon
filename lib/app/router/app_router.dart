/// Main application router with stateful shell navigation
///
/// This router defines the shell structure with multiple branches (tabs).
/// Each branch corresponds to a main section of the app.
///
/// Structure:
/// - DashboardShell (bottom navigation)
///   - Home branch
///   - Control branch
///   - Chat branch
///   - Settings branch
///   - Profile branch
@TypedStatefulShellRoute<DashboardShellRoute>(
  branches: [
    TypedStatefulShellBranch<HomeBranch>(
      routes: [TypedGoRoute<HomeRoute>(path: '/home')],
    ),
    TypedStatefulShellBranch<ControlBranch>(
      routes: [TypedGoRoute<ControlRoute>(path: '/control')],
    ),
    TypedStatefulShellBranch<ChatBranch>(
      routes: [TypedGoRoute<ChatRoute>(path: '/chat')],
    ),
    TypedStatefulShellBranch<SettingsBranch>(
      routes: [TypedGoRoute<SettingsRoute>(path: '/settings')],
    ),
    TypedStatefulShellBranch<ProfileBranch>(
      routes: [TypedGoRoute<ProfileRoute>(path: '/profile')],
    ),
  ],
)
class DashboardShellRoute extends StatefulShellRouteData {
  const DashboardShellRoute();

  @override
  Widget builder(
    BuildContext context,
    GoRouterState state,
    StatefulNavigationShell navigationShell,
  ) {
    return DashboardShell(navigationShell: navigationShell);
  }
}

/// Home branch - Main screen of the app
class HomeBranch extends StatefulShellBranchData {
  const HomeBranch();
  static const String $initialLocation = '/home';
}

/// Control branch - Control functionality
class ControlBranch extends StatefulShellBranchData {
  const ControlBranch();
  static const String $initialLocation = '/control';
}

/// Chat branch - User chat
class ChatBranch extends StatefulShellBranchData {
  const ChatBranch();
  static const String $initialLocation = '/chat';
}

/// Settings branch - User settings
class SettingsBranch extends StatefulShellBranchData {
  const SettingsBranch();
  static const String $initialLocation = '/settings';
}

/// Profile branch - User profile and settings
class ProfileBranch extends StatefulShellBranchData {
  const ProfileBranch();
  static const String $initialLocation = '/profile';
}

/// Builds and configures the main application router
///
/// The router is configured with:
/// - Type-safe routes generated by go_router_builder
/// - Initial location set to /home
/// - Stateful shell for bottom navigation
/// - Mock selector route (only when MOCK=true)
GoRouter buildAppRouter() {
  // Mock routes are only available when MOCK environment variable is set
  // Run with: flutter run --dart-define=MOCK=true
  final mockRoutes = const bool.fromEnvironment('MOCK')
      ? [$mockSelectorRoute]
      : <RouteBase>[];

  return GoRouter(
    initialLocation: '/',
    redirect: (context, state) {
      final isSplash = state.matchedLocation == '/';
      if (isSplash) return null;

      final user = FirebaseAuth.instance.currentUser;
      final isOnAuth = state.matchedLocation.startsWith('/auth');

      if (user == null && !isOnAuth) return '/auth';
      if (user != null && user.emailVerified && isOnAuth) return '/home';

      return null;
    },
    refreshListenable: _AuthStateListenable(),
    routes: [
      GoRoute(path: '/', builder: (context, state) => const SplashScreen()),
      ...$appRoutes,
      $authRoute,
      $profileRoute,
      $trustedContactsRoute,
      $protectedPeopleRoute,
      $panicButtonRoute,
      $alertDetailRoute,
      ...mockRoutes,
    ],
  );
}

/// Listenable that notifies when the authentication state changes
class _AuthStateListenable extends ChangeNotifier {
  _AuthStateListenable() {
    FirebaseAuth.instance.idTokenChanges().listen((_) => notifyListeners());
  }
}
